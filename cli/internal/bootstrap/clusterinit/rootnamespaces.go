package clusterinit

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// rootNamespacesFileName holds the Namespaces that root-level overlay objects
// live in. The root Kustomization (flux-system) applies the private-CA
// ConfigMap and the BYO wildcard Secrets, but their namespaces are created by
// later layers that depend on the root. On a fresh cluster the root therefore
// never applied and nothing else could start (CloudFerro rehearsal,
// 2026-10-31). Flux applies Namespaces before other objects in one apply.
const rootNamespacesFileName = "root-namespaces.yaml"

// ensureRootNamespaces adds namespaces to the overlay's root Namespace list
// and wires the file into the cluster kustomization. Each Namespace is created
// only if absent and never pruned, so the layer that owns it keeps its labels
// and removing it from this file cannot delete a namespace.
func ensureRootNamespaces(clusterDir string, namespaces []string) error {
	path := filepath.Join(clusterDir, rootNamespacesFileName)
	want := map[string]bool{}
	if body, err := os.ReadFile(path); err == nil {
		for _, line := range strings.Split(string(body), "\n") {
			if name, ok := strings.CutPrefix(line, "  name: "); ok {
				want[strings.TrimSpace(name)] = true
			}
		}
	} else if !os.IsNotExist(err) {
		return fmt.Errorf("root namespaces: read %s: %w", path, err)
	}
	for _, ns := range namespaces {
		// flux-system is created by the bootstrap manifests in the same root.
		if ns != "" && ns != "flux-system" {
			want[ns] = true
		}
	}
	if len(want) == 0 {
		return nil
	}
	names := make([]string, 0, len(want))
	for ns := range want {
		names = append(names, ns)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("# Namespaces for objects the root Kustomization applies (private-CA trust,\n")
	b.WriteString("# operator-supplied TLS). Generated by `kube-dc bootstrap init`. Created only\n")
	b.WriteString("# when absent and never pruned; the platform layers own their labels.\n")
	for _, ns := range names {
		b.WriteString("---\napiVersion: v1\nkind: Namespace\nmetadata:\n")
		b.WriteString("  name: " + ns + "\n")
		b.WriteString("  annotations:\n")
		b.WriteString("    kustomize.toolkit.fluxcd.io/ssa: IfNotPresent\n")
		b.WriteString("    kustomize.toolkit.fluxcd.io/prune: disabled\n")
	}
	if existing, err := os.ReadFile(path); err != nil || string(existing) != b.String() {
		if err := atomicWrite(path, []byte(b.String()), 0o644); err != nil {
			return fmt.Errorf("root namespaces: write %s: %w", path, err)
		}
	}
	if err := patchFileLines(filepath.Join(clusterDir, "kustomization.yaml"), patchKustomizationResource(rootNamespacesFileName)); err != nil {
		return fmt.Errorf("root namespaces: patch kustomization.yaml: %w", err)
	}
	return nil
}
