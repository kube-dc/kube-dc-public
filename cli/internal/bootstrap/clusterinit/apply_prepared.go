package clusterinit

import (
	"context"
	"fmt"
	"io"
	"reflect"
	"sort"

	"github.com/shalb/kube-dc/cli/internal/bootstrap/ports"
)

func applyPrepared(ctx context.Context, opts ApplyOptions) error {
	if _, ok := opts.Reporter.(StepExecutor); !ok {
		return fmt.Errorf("prepared apply requires an abortable execution guard")
	}
	checker, ok := opts.Reporter.(ExecutionChecker)
	if !ok {
		return fmt.Errorf("prepared apply requires a live ownership checker")
	}
	p := *opts.Prepared
	if p.Destination != opts.FleetRepo || p.Cluster != opts.Plan.ClusterName || opts.KubeconfigPath == "" || opts.K8s == nil {
		return fmt.Errorf("prepared apply destination or explicit child access differs")
	}
	if err := VerifyPreparedScaffold(p); err != nil {
		return err
	}
	if !opts.NoPush {
		if err := CheckProviderHostSupport(opts.FleetRepo, opts.Provider, opts.ProviderHost); err != nil {
			return err
		}
		binder, ok := opts.Git.(ports.GitProviderBinder)
		if !ok {
			return fmt.Errorf("prepared apply requires a provider-bound Git adapter")
		}
		host, err := applyProviderHost(ctx, opts)
		if err != nil {
			return err
		}
		opts.Git, err = binder.ForProvider(ctx, opts.FleetRepo, host)
		if err != nil {
			return err
		}
	}
	out := opts.Out
	if out == nil {
		out = io.Discard
	}
	if !opts.NoPush {
		if err := ExecuteStep(opts.Reporter, StepIngressNodes, func() error {
			return EnsureIngressNodeLabels(ctx, opts.K8s, opts.Plan.IngressNodes, opts.Plan.IngressNodeLabel, out)
		}); err != nil {
			return err
		}
	}
	if err := ExecuteStep(opts.Reporter, StepScaffold, func() error {
		return PublishPreparedScaffold(ctx, p, opts.FleetRepo, checker.CheckExecution)
	}); err != nil {
		return err
	}
	if err := ExecuteStep(opts.Reporter, StepCommitPush, func() error {
		// The coordinator checks the exact reviewed/receipt-bound tree before
		// admission. Never reset a commit after a transport error: the remote
		// may already contain it, and recovery must inspect that identity.
		diff, err := opts.Git.Diff(ctx, opts.FleetRepo)
		if err != nil {
			return err
		}
		if len(diff.Files) == 0 {
			if opts.NoPush {
				return nil
			}
			return opts.Git.Push(ctx, opts.FleetRepo, opts.GitHubToken)
		}
		_, err = commitAndMaybePush(ctx, opts, fmt.Sprintf("feat(%s): publish reviewed bootstrap", p.Cluster))
		return err
	}); err != nil {
		return err
	}
	if opts.NoPush {
		opts.Reporter.Skip(StepFluxInstall, "--no-push")
		return nil
	}
	return ExecuteStep(opts.Reporter, StepFluxInstall, func() error { return runFluxInstall(ctx, opts, out) })
}

// SnapshotPreparedFleet records non-secret file metadata for the selected
// cluster and shared generator sources, including an absent cluster directory.
func SnapshotPreparedFleet(p PreparedScaffold) ([]PreparedFile, error) {
	source, err := SnapshotScaffoldSource(p.Destination, p.SiteComponents...)
	if err != nil {
		return nil, err
	}
	cluster, err := snapshotTree(p.Destination, "clusters/"+p.Cluster, true)
	if err != nil {
		return nil, err
	}
	return append(source, cluster...), nil
}

// VerifyPreparedPublication checks exact generated bytes and source additions.
// It never treats a partial directory as a completed scaffold.
func VerifyPreparedPublication(p PreparedScaffold) error {
	if err := VerifyPreparedScaffold(p); err != nil {
		return err
	}
	source, err := SnapshotScaffoldSource(p.Destination, p.SiteComponents...)
	if err != nil || !reflect.DeepEqual(source, p.SourceAfter) {
		return fmt.Errorf("published shared source differs from the prepared review")
	}
	cluster, err := snapshotTree(p.Destination, "clusters/"+p.Cluster, false)
	if err != nil {
		return err
	}
	added, err := reviewedSourceAdditions(p.SourceFiles, p.SourceAfter)
	if err != nil {
		return err
	}
	files := append(cluster, added...)
	// Prepared files are sorted across the cluster and shared paths.
	sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })
	if !reflect.DeepEqual(files, p.Files) {
		return fmt.Errorf("published cluster differs from the exact prepared bytes")
	}
	return nil
}
